import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { tokensToCss, tokensToTailwind, cssName } from "../tokens-to-css.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const sample = JSON.parse(readFileSync(join(here, "tokens-export.sample.json"), "utf8"));

test("cssName turns token paths into custom property names", () => {
  assert.equal(cssName("color.brand.primary"), "--color-brand-primary");
  assert.equal(cssName("Font Size.2XL"), "--font-size-2xl");
});

test("later active set wins for duplicate names", () => {
  const { css } = tokensToCss(sample, "tokens.json");
  assert.match(css, /--color-brand-primary: #2563EB;/);
  assert.doesNotMatch(css, /#1D4ED8/);
});

test("inactive sets are excluded", () => {
  const { css } = tokensToCss(sample);
  assert.doesNotMatch(css, /color-draft-only/);
});

test("unitless dimensions get px, values that already have units are kept", () => {
  const { css } = tokensToCss(sample);
  assert.match(css, /--spacing-md: 16px;/);
  assert.match(css, /--font-size-2xl: 28px;/);
  assert.match(css, /--radius-full: 9999px;/);
});

test("font families are quoted when needed and keep their real names", () => {
  const { css } = tokensToCss(sample);
  assert.match(css, /--font-family-body: "Atkinson Hyperlegible";/);
  assert.match(css, /--font-family-heading: Outfit;/);
});

test("alias values become var() references", () => {
  const { css } = tokensToCss(sample);
  assert.match(css, /--color-text-default: var\(--color-text-primary\);/);
});

test("types without a CSS form are reported, not silently dropped", () => {
  const { skipped, css } = tokensToCss(sample);
  assert.ok(skipped.some(s => s.includes("shadow.card")));
  assert.doesNotMatch(css, /shadow-card/);
});

test("output is deterministic and wrapped in :root by default", () => {
  const a = tokensToCss(sample).css;
  const b = tokensToCss(sample).css;
  assert.equal(a, b);
  assert.match(a, /^\/\* Generated by penpot-power/);
  assert.match(a, /:root \{\n/);
});

test("supports @theme wrapper for Tailwind v4", () => {
  const { css } = tokensToCss(sample, "tokens.json", { wrapper: "@theme" });
  assert.match(css, /@theme \{\n/);
  assert.match(css, /--color-brand-primary: #2563EB;/);
});

test("tokensToTailwind produces valid Tailwind v3 configuration object", () => {
  const { js, theme } = tokensToTailwind(sample);
  assert.match(js, /module\.exports =/);
  assert.equal(theme.colors["brand-primary"], "#2563EB");
  assert.equal(theme.spacing["md"], "16px");
  assert.equal(theme.borderRadius["full"], "9999px");
  assert.equal(theme.fontSize["2xl"], "28px");
  assert.deepEqual(theme.fontFamily["body"], ["Atkinson Hyperlegible"]);
});

test("rejects input without a sets array", () => {
  assert.throws(() => tokensToCss({}), /sets/);
  assert.throws(() => tokensToTailwind({}), /sets/);
});
